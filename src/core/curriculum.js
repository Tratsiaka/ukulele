/** Уроки по id. @type {Record<string, Lesson>} */
export const LESSONS = Object.fromEntries(LESSON_LIST.map((l) => [l.id, l]));

/**
 * Уровень по id.
 * @param {string} id
 * @returns {Level|null}
 */
export function levelById(id) {
  return LEVELS.find((l) => l.id === id) ?? null;
}

/**
 * Урок по id.
 * @param {string} id
 * @returns {Lesson|null}
 */
export function lessonById(id) {
  return LESSONS[id] ?? null;
}

/**
 * Бой по id.
 * @param {string} id
 * @returns {StrumPattern|null}
 */
export function strumById(id) {
  return STRUM_PATTERNS.find((p) => p.id === id) ?? null;
}

/**
 * Уроки уровня по порядку.
 * @param {string} levelId
 * @returns {Lesson[]}
 */
export function lessonsOfLevel(levelId) {
  return (levelById(levelId)?.lessons ?? []).map((id) => LESSONS[id]).filter(Boolean);
}

/**
 * Все аккорды, выученные к концу уровня включительно (без запасных bonus).
 * @param {string} levelId
 * @returns {string[]}
 */
export function knownChordsAfter(levelId) {
  const idx = LEVELS.findIndex((l) => l.id === levelId);
  if (idx < 0) return [];
  return LEVELS.slice(0, idx + 1).flatMap((l) => l.chords);
}

/**
 * Уровень, на котором аккорд появляется (основной или запасной). Неизвестный → null.
 * @param {string} name нормализованное имя
 * @returns {Level|null}
 */
export function levelOfChord(name) {
  return LEVELS.find((l) => l.chords.includes(name) || l.bonus?.includes(name)) ?? null;
}

const CHORD_ORDER = LEVELS.flatMap((l) => [...l.chords, ...(l.bonus ?? [])]);

/**
 * Место аккорда в учебном порядке (для сортировки). Аккорды вне пути — в конец.
 * @param {string} name
 * @returns {number}
 */
export function chordRank(name) {
  const i = CHORD_ORDER.indexOf(name);
  return i < 0 ? CHORD_ORDER.length : i;
}

/**
 * Пройден ли урок.
 * @param {{lessonsDone?: Record<string, string>}} progress
 * @param {string} lessonId
 */
export function isLessonDone(progress, lessonId) {
  return Boolean(progress?.lessonsDone?.[lessonId]);
}

/**
 * Сколько уроков уровня пройдено.
 * @param {{lessonsDone?: Record<string, string>}} progress
 * @param {string} levelId
 * @returns {{done: number, total: number, complete: boolean}}
 */
export function levelProgress(progress, levelId) {
  const ids = levelById(levelId)?.lessons ?? [];
  const done = ids.filter((id) => isLessonDone(progress, id)).length;
  return { done, total: ids.length, complete: ids.length > 0 && done === ids.length };
}

/**
 * Текущий уровень — первый, где остались непройденные уроки. Всё пройдено → последний.
 * @param {{lessonsDone?: Record<string, string>}} progress
 * @returns {Level}
 */
export function currentLevel(progress) {
  return LEVELS.find((l) => !levelProgress(progress, l.id).complete) ?? LEVELS[LEVELS.length - 1];
}

/**
 * Следующий непройденный урок по порядку пути. Всё пройдено → null.
 * @param {{lessonsDone?: Record<string, string>}} progress
 * @returns {Lesson|null}
 */
export function nextLesson(progress) {
  for (const level of LEVELS) {
    for (const id of level.lessons) if (!isLessonDone(progress, id)) return LESSONS[id] ?? null;
  }
  return null;
}

/**
 * Цель OMC для пары с учётом текущего уровня: свежая пара — цель её уровня,
 * старая — самая высокая цель, пройденная с тех пор (C–G на L3 → 50, F–Bb на L4 → 30).
 * @param {{lessonsDone?: Record<string, string>}} progress
 * @param {string} a
 * @param {string} b
 * @returns {number}
 */
export function omcTarget(progress, a, b) {
  const cur = LEVELS.indexOf(currentLevel(progress));
  const idx = (name) => {
    const l = levelOfChord(name);
    return l ? LEVELS.indexOf(l) : cur;
  };
  const pairIdx = Math.max(idx(a), idx(b));
  if (pairIdx >= cur) return LEVELS[pairIdx].omc;
  return Math.max(...LEVELS.slice(pairIdx, cur + 1).map((l) => l.omc));
}
